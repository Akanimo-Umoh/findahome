import type { jsPDF } from "jspdf"
import { formatReceiptDate, receiptFilename, type ReceiptData } from "./receipt"

// jsPDF's built-in fonts have no naira sign, so the PDF writes "NGN".
const ngn = (n: number) => `NGN ${n.toLocaleString("en-NG")}`

const BRAND: [number, number, number] = [39, 74, 208]
const INK: [number, number, number] = [17, 24, 39]
const MUTED: [number, number, number] = [107, 114, 128]
const LINE: [number, number, number] = [229, 231, 235]
const SOFT: [number, number, number] = [238, 242, 255]

const MARGIN = 16
const PAGE_W = 210
const PAGE_H = 297
const RIGHT = PAGE_W - MARGIN
const CONTENT_W = PAGE_W - MARGIN * 2

// Draws the receipt on A4. All text is real (selectable) text, no screenshot.
export async function buildReceiptPdf(r: ReceiptData): Promise<jsPDF> {
  const { jsPDF } = await import("jspdf")
  const doc = new jsPDF({ unit: "mm", format: "a4" })
  let y = 0

  const text = (
    value: string,
    x: number,
    at: number,
    opts: {
      size?: number
      bold?: boolean
      color?: [number, number, number]
      align?: "left" | "right" | "center"
    } = {}
  ) => {
    doc.setFont("helvetica", opts.bold ? "bold" : "normal")
    doc.setFontSize(opts.size ?? 10)
    doc.setTextColor(...(opts.color ?? INK))
    doc.text(value, x, at, { align: opts.align ?? "left" })
  }

  const rule = (at: number) => {
    doc.setDrawColor(...LINE)
    doc.setLineWidth(0.3)
    doc.line(MARGIN, at, RIGHT, at)
  }

  const footer = (page: number, pages: number) => {
    rule(PAGE_H - 18)
    text(
      `Generated by FindaHome on ${formatReceiptDate(new Date().toISOString())}. This receipt is proof of the payment above.`,
      MARGIN,
      PAGE_H - 12,
      { size: 8, color: MUTED }
    )
    text(`Page ${page} of ${pages}`, RIGHT, PAGE_H - 12, {
      size: 8,
      color: MUTED,
      align: "right",
    })
  }

  const ensure = (needed: number) => {
    if (y + needed > PAGE_H - 24) {
      doc.addPage()
      y = 20
    }
  }

  const heading = (title: string) => {
    ensure(14)
    text(title.toUpperCase(), MARGIN, y, {
      size: 8.5,
      bold: true,
      color: MUTED,
    })
    y += 2
    rule(y)
    y += 6
  }

  const row = (label: string, value: string) => {
    const lines = doc.splitTextToSize(value, CONTENT_W - 58) as string[]
    ensure(lines.length * 5 + 2)
    text(label, MARGIN, y, { size: 9.5, color: MUTED })
    lines.forEach((line, i) => {
      text(line, MARGIN + 58, y + i * 5, { size: 9.5 })
    })
    y += lines.length * 5 + 1.5
  }

  // ---- header band
  doc.setFillColor(...BRAND)
  doc.rect(0, 0, PAGE_W, 30, "F")
  text("FindaHome", MARGIN, 14, {
    size: 20,
    bold: true,
    color: [255, 255, 255],
  })
  text("Payment receipt", MARGIN, 21, { size: 10, color: [219, 228, 255] })
  text(r.receiptNo, RIGHT, 13, {
    size: 12,
    bold: true,
    color: [255, 255, 255],
    align: "right",
  })
  text(`Issued ${formatReceiptDate(new Date().toISOString())}`, RIGHT, 20, {
    size: 8.5,
    color: [219, 228, 255],
    align: "right",
  })

  // ---- amount card
  y = 38
  doc.setFillColor(...SOFT)
  doc.roundedRect(MARGIN, y, CONTENT_W, 24, 3, 3, "F")
  text("AMOUNT PAID", MARGIN + 6, y + 8, {
    size: 8.5,
    bold: true,
    color: MUTED,
  })
  text(ngn(r.amount), MARGIN + 6, y + 18, {
    size: 20,
    bold: true,
    color: BRAND,
  })
  const badge = r.statusLabel.toUpperCase()
  doc.setFont("helvetica", "bold")
  doc.setFontSize(8.5)
  const badgeW = doc.getTextWidth(badge) + 10
  doc.setFillColor(...BRAND)
  doc.roundedRect(RIGHT - 6 - badgeW, y + 8, badgeW, 8, 4, 4, "F")
  text(badge, RIGHT - 6 - badgeW / 2, y + 13.3, {
    size: 8.5,
    bold: true,
    color: [255, 255, 255],
    align: "center",
  })
  y += 32

  // ---- property
  heading("Property")
  text(r.property.title, MARGIN, y, { size: 12, bold: true })
  y += 6
  if (r.property.address) {
    const addr = doc.splitTextToSize(r.property.address, CONTENT_W) as string[]
    addr.forEach((line, i) =>
      text(line, MARGIN, y + i * 5, { size: 9.5, color: MUTED })
    )
    y += addr.length * 5
  }
  text(`Ref: ${r.property.ref}`, MARGIN, y, { size: 9.5, color: MUTED })
  y += 9

  // ---- payment details
  heading("Payment details")
  row("Payment type", r.typeLabel)
  row("Date paid", formatReceiptDate(r.paidAt))
  row("Payment reference", r.reference ?? "—")
  row("Paid through", "Paystack")
  y += 3

  // ---- buyer and agent, side by side
  heading("Parties")
  const colW = CONTENT_W / 2
  const block = (title: string, p: ReceiptData["buyer"], x: number) => {
    text(title, x, y, { size: 8.5, bold: true, color: BRAND })
    text(p.name, x, y + 6, { size: 10.5, bold: true })
    text(p.email || "—", x, y + 11.5, { size: 9, color: MUTED })
    text(p.phone, x, y + 16.5, { size: 9, color: MUTED })
  }
  ensure(24)
  block("BUYER", r.buyer, MARGIN)
  block("AGENT", r.agent, MARGIN + colW)
  y += 27

  // ---- breakdown
  heading("Breakdown")
  r.lines.forEach((line) => {
    ensure(8)
    text(line.label, MARGIN, y, { size: 10 })
    text(ngn(line.amount), RIGHT, y, { size: 10, align: "right" })
    y += 6.5
  })
  rule(y - 3)
  y += 3
  text("Total paid", MARGIN, y, { size: 11, bold: true })
  text(ngn(r.amount), RIGHT, y, {
    size: 11,
    bold: true,
    color: BRAND,
    align: "right",
  })
  y += 8

  // ---- timeline
  heading("Transaction timeline")
  r.timeline.forEach((step) => {
    ensure(10)
    if (step.done) {
      doc.setFillColor(...BRAND)
      doc.circle(MARGIN + 2, y - 1.2, 1.7, "F")
    } else {
      doc.setDrawColor(...LINE)
      doc.setLineWidth(0.4)
      doc.circle(MARGIN + 2, y - 1.2, 1.7, "S")
    }
    text(step.label, MARGIN + 8, y, {
      size: 10,
      color: step.done ? INK : MUTED,
    })
    if (step.at) {
      text(formatReceiptDate(step.at), RIGHT, y, {
        size: 9,
        color: MUTED,
        align: "right",
      })
    }
    y += 6
  })
  y += 3

  // ---- note
  const note = doc.splitTextToSize(r.note, CONTENT_W - 12) as string[]
  ensure(note.length * 5 + 10)
  doc.setFillColor(...SOFT)
  doc.roundedRect(MARGIN, y, CONTENT_W, note.length * 5 + 8, 3, 3, "F")
  note.forEach((line, i) =>
    text(line, MARGIN + 6, y + 7 + i * 5, { size: 9.5 })
  )

  // ---- footers
  const pages = doc.getNumberOfPages()
  for (let p = 1; p <= pages; p++) {
    doc.setPage(p)
    footer(p, pages)
  }

  return doc
}

export async function downloadReceiptPdf(r: ReceiptData) {
  const doc = await buildReceiptPdf(r)
  doc.save(receiptFilename(r))
}
